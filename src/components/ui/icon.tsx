export type IconName = keyof typeof ICONS;

/**
 * A decorative icon (hidden from screen readers; the text next to it carries
 * the meaning). Size it with `size-*` (default 20px); colour follows the text.
 */
export function Icon({
  name,
  className,
  ...props
}: { name: IconName } & Omit<SVGProps<SVGSVGElement>, "ref" | "name">) {
  const Glyph = ICONS[name];
  return <Glyph aria-hidden="true" focusable="false" strokeWidth={1.5} className={cn("size-5 shrink-0", className)} {...props} />;
}
